/**
 * AI Assistant page (T7.4, RULES B1, B5, E2, ARCHITECTURE 11).
 * Features:
 * - 5 interaction modes (Ask, Explain File, Find Bugs, Architecture, Improvements)
 * - File picker populated from repository file inventory
 * - Chat thread with full query history
 * - Citation chips [path:start-end] opening side code viewer
 * - Safety & verification warning banners
 * - Strict text-only rendering via textContent (XSS immune)
 */

import { api } from "../api.js";
import { state } from "../state.js";
import { h } from "../ui/h.js";
import { renderSkeleton } from "../ui/skeleton.js";
import { showToast } from "../ui/toast.js";

const MODES = [
  { id: "ask", label: "Ask Question", desc: "General repository Q&A" },
  { id: "explain_file", label: "Explain File", desc: "Detailed walkthrough of selected file" },
  { id: "find_bugs", label: "Find Bugs", desc: "Edge cases & bugs (AI suggestion, not verified)" },
  { id: "summarize_architecture", label: "Architecture", desc: "High-level component flow" },
  { id: "suggest_improvements", label: "Improvements", desc: "Refactoring & test coverage suggestions" },
];

let activeMessages = [];
let availableFiles = [];
let selectedChunk = null;
let currentMode = "ask";

export default {
  title: "AI Assistant",

  async mount(ctx) {
    const container = ctx.container || ctx;
    container.innerHTML = "";
    selectedChunk = null;

    const analysisId = state.get("analysisId");
    if (!analysisId) {
      container.appendChild(
        h(
          "div",
          { class: "empty-state p-8 text-center" },
          h("h3", { class: "text-lg font-semibold mb-2" }, "No Repository Selected"),
          h("p", { class: "text-neutral-500 mb-4" }, "Analyze a GitHub repository first to query the AI assistant."),
          h(
            "a",
            { href: "#/analyzer", class: "btn btn-primary" },
            "Go to Analyzer"
          )
        )
      );
      return;
    }

    // Render loading skeleton
    const skeleton = renderSkeleton("card", 3);
    container.appendChild(skeleton);

    try {
      // Fetch repository files for file picker
      const qualData = await api.getQualityData(analysisId);
      const lizardFiles = qualData.data?.components?.complexity?.details?.hotspots || [];
      const inventoryFiles = qualData.data?.files || [];
      const fileSet = new Set();

      lizardFiles.forEach((f) => f.file && fileSet.add(f.file));
      inventoryFiles.forEach((f) => f.path && fileSet.add(f.path));

      availableFiles = Array.from(fileSet).sort();
    } catch {
      availableFiles = [];
    } finally {
      container.innerHTML = "";
    }

    renderAssistantLayout(container, analysisId);
  },

  unmount() {
    selectedChunk = null;
  },
};

function renderAssistantLayout(container, analysisId) {
  // 1. Safety banner
  const disclaimerBanner = h(
    "div",
    {
      class: "disclaimer-banner flex items-center gap-3 p-3.5 mb-5 rounded-lg border border-amber-500/20 bg-amber-500/10 text-amber-300 text-xs",
    },
    h(
      "span",
      { class: "badge badge-warning font-mono uppercase text-[10px]" },
      "Disclaimer"
    ),
    h(
      "p",
      { class: "flex-1" },
      "AI suggestions are generated by an LLM and not formally verified. Code citations are verified against real repository files. Untrusted repository strings are rendered strictly as text."
    )
  );

  // 2. Control bar (Mode selector + File picker)
  const modeTabs = h(
    "div",
    { class: "flex flex-wrap gap-1.5 p-1 bg-neutral-900 border border-neutral-800 rounded-lg mb-4" },
    ...MODES.map((m) =>
      h(
        "button",
        {
          class: `px-3 py-1.5 text-xs font-medium rounded-md transition-colors ${
            currentMode === m.id
              ? "bg-neutral-800 text-white shadow-sm"
              : "text-neutral-400 hover:text-neutral-200"
          }`,
          onclick: (e) => {
            currentMode = m.id;
            updateModeSelection(e.target);
            updateFilePickerVisibility();
          },
        },
        m.label
      )
    )
  );

  const fileSelect = h(
    "select",
    {
      id: "assistant-file-picker",
      class: "form-select text-xs py-1.5 px-3 bg-neutral-900 border border-neutral-800 rounded-md text-neutral-200 w-full sm:w-72",
    },
    h("option", { value: "" }, "-- Select Target File (optional) --"),
    ...availableFiles.map((f) => h("option", { value: f }, f))
  );

  const filePickerContainer = h(
    "div",
    {
      id: "file-picker-wrapper",
      class: "flex items-center gap-2 mb-4",
    },
    h("label", { class: "text-xs font-medium text-neutral-400" }, "File context:"),
    fileSelect
  );

  // 3. Two-column split layout (Left: Chat Thread & Input, Right: Code Inspector Panel)
  const threadContainer = h("div", {
    id: "assistant-thread",
    class: "flex flex-col gap-4 overflow-y-auto max-h-[520px] p-4 bg-neutral-950 border border-neutral-800 rounded-lg min-h-[320px]",
  });

  const codeInspector = h(
    "div",
    {
      id: "assistant-code-inspector",
      class: "flex flex-col bg-neutral-950 border border-neutral-800 rounded-lg p-4 h-[580px] overflow-hidden",
    },
    h("div", { class: "flex items-center justify-between border-b border-neutral-800 pb-2 mb-3" },
      h("h4", { class: "text-xs font-semibold uppercase tracking-wider text-neutral-400" }, "Code Inspector"),
      h("span", { id: "inspector-badge", class: "text-[11px] text-neutral-500 font-mono" }, "No citation selected")
    ),
    h(
      "pre",
      {
        id: "inspector-content",
        class: "flex-1 overflow-auto text-xs font-mono p-3 bg-neutral-900 rounded border border-neutral-800 text-neutral-300 whitespace-pre",
      },
      "Click any citation chip or retrieved chunk to view its source lines here."
    )
  );

  // Render previous thread messages if any
  renderThreadMessages(threadContainer);

  // 4. Input bar
  const queryInput = h("textarea", {
    id: "assistant-query-input",
    class: "w-full bg-neutral-900 border border-neutral-800 rounded-lg p-3 text-sm text-neutral-100 placeholder-neutral-500 focus:outline-none focus:border-indigo-500 resize-none h-20",
    placeholder: "Ask about this repository (e.g., 'How are user sessions managed?', 'Explain calculate_cart_total')...",
  });

  const sendBtn = h(
    "button",
    {
      class: "btn btn-primary px-4 py-2 text-xs font-semibold flex items-center gap-2 self-end",
      onclick: async () => {
        const text = queryInput.value.trim();
        const targetFile = fileSelect.value || null;
        if (!text && currentMode === "ask") {
          showToast("Please enter a question or topic.", "warning");
          return;
        }

        await handleAssistantSubmit({
          analysisId,
          mode: currentMode,
          question: text,
          filePath: targetFile,
          threadContainer,
          sendBtn,
          queryInput,
        });
      },
    },
    "Send Query"
  );

  const inputForm = h(
    "div",
    { class: "flex flex-col gap-2 mt-4" },
    queryInput,
    h("div", { class: "flex justify-between items-center" },
      h("span", { class: "text-[11px] text-neutral-500" }, "Press Send Query to retrieve code context."),
      sendBtn
    )
  );

  const mainColumns = h(
    "div",
    { class: "grid grid-cols-1 lg:grid-cols-12 gap-5" },
    h("div", { class: "lg:col-span-7 flex flex-col" }, threadContainer, inputForm),
    h("div", { class: "lg:col-span-5" }, codeInspector)
  );

  container.appendChild(disclaimerBanner);
  container.appendChild(modeTabs);
  container.appendChild(filePickerContainer);
  container.appendChild(mainColumns);

  function updateModeSelection(btn) {
    const parent = btn.parentElement;
    parent.querySelectorAll("button").forEach((b) => {
      b.className = "px-3 py-1.5 text-xs font-medium rounded-md transition-colors text-neutral-400 hover:text-neutral-200";
    });
    btn.className = "px-3 py-1.5 text-xs font-medium rounded-md transition-colors bg-neutral-800 text-white shadow-sm";
  }

  function updateFilePickerVisibility() {
    if (currentMode === "explain_file") {
      filePickerContainer.classList.add("ring-1", "ring-indigo-500/50");
    } else {
      filePickerContainer.classList.remove("ring-1", "ring-indigo-500/50");
    }
  }
}

function renderThreadMessages(threadContainer) {
  threadContainer.innerHTML = "";

  if (activeMessages.length === 0) {
    threadContainer.appendChild(
      h(
        "div",
        { class: "text-center p-8 text-neutral-500 text-xs flex flex-col items-center gap-2" },
        h("div", { class: "text-lg opacity-40" }, "[ ? ]"),
        h("p", {}, "No queries yet. Select a mode, enter a question or target file, and send.")
      )
    );
    return;
  }

  for (const msg of activeMessages) {
    const isUser = msg.role === "user";

    const bubble = h(
      "div",
      {
        class: `flex flex-col p-3.5 rounded-lg max-w-[90%] text-xs ${
          isUser
            ? "self-end bg-indigo-600/20 border border-indigo-500/30 text-indigo-100"
            : "self-start bg-neutral-900 border border-neutral-800 text-neutral-200"
        }`,
      },
      h("div", { class: "flex items-center justify-between mb-1 text-[10px] text-neutral-400 font-mono" },
        h("span", { class: "font-bold uppercase" }, isUser ? "You" : "Assistant"),
        msg.mode ? h("span", { class: "badge badge-neutral text-[9px]" }, msg.mode) : null
      ),
      // STRICT TEXT CONTENT RENDERING (RULES B5 & E2)
      h("p", { class: "whitespace-pre-wrap leading-relaxed", id: "msg-text" }, msg.text)
    );

    // Citations list
    if (msg.citations && msg.citations.length > 0) {
      const citeChips = h(
        "div",
        { class: "flex flex-wrap gap-1.5 mt-2.5 pt-2 border-t border-neutral-800/80" },
        h("span", { class: "text-[10px] text-neutral-500 font-mono self-center mr-1" }, "Citations:"),
        ...msg.citations.map((c) =>
          h(
            "button",
            {
              class: "btn btn-outline text-[11px] py-0.5 px-2 font-mono hover:border-indigo-400 hover:text-indigo-300",
              onclick: () => inspectCitation(c, msg.chunks),
            },
            c.citation || `${c.path}:${c.start_line}-${c.end_line}`
          )
        )
      );
      bubble.appendChild(citeChips);
    }

    // Warnings list
    if (msg.warnings && msg.warnings.length > 0) {
      const warnBox = h(
        "div",
        { class: "mt-2 p-2 bg-amber-500/10 border border-amber-500/20 rounded text-[11px] text-amber-300" },
        ...msg.warnings.map((w) => h("p", {}, w))
      );
      bubble.appendChild(warnBox);
    }

    // Unconfigured LLM note banner
    if (msg.note === "LLM_NOT_CONFIGURED") {
      const noteBox = h(
        "div",
        { class: "mt-2 p-2 bg-blue-500/10 border border-blue-500/20 rounded text-[11px] text-blue-300" },
        h("p", { class: "font-medium" }, "LLM provider is not configured."),
        h("p", { class: "text-[10px] opacity-80 mt-0.5" }, "Retrieved chunks are shown below. Configure LLM_PROVIDER and LLM_API_KEY in .env to enable generative replies.")
      );
      bubble.appendChild(noteBox);
    }

    // Retrieved chunks list if returned
    if (msg.chunks && msg.chunks.length > 0 && !isUser) {
      const chunksToggle = h(
        "details",
        { class: "mt-2 text-[11px] border border-neutral-800/50 rounded p-1.5" },
        h("summary", { class: "cursor-pointer text-neutral-400 hover:text-neutral-200" }, `Retrieved Context Chunks (${msg.chunks.length})`),
        h(
          "div",
          { class: "flex flex-col gap-1.5 mt-2" },
          ...msg.chunks.map((chk) =>
            h(
              "button",
              {
                class: "text-left p-1.5 bg-neutral-950 rounded hover:bg-neutral-800/50 text-[10px] font-mono text-neutral-300 truncate",
                onclick: () => inspectChunk(chk),
              },
              `${chk.path} (L${chk.start_line}-${chk.end_line}) - score ${chk.score}`
            )
          )
        )
      );
      bubble.appendChild(chunksToggle);
    }

    threadContainer.appendChild(bubble);
  }

  threadContainer.scrollTop = threadContainer.scrollHeight;
}

function inspectCitation(citation, chunks = []) {
  const badge = document.getElementById("inspector-badge");
  const content = document.getElementById("inspector-content");
  if (!badge || !content) return;

  const targetPath = citation.path;
  badge.textContent = `${targetPath} : L${citation.start_line}-${citation.end_line}`;

  // Find matching chunk if available
  const match = (chunks || []).find((c) => c.path === targetPath || targetPath.endsWith(c.path));
  if (match) {
    content.textContent = match.text;
  } else {
    content.textContent = `Referenced location: ${targetPath} (Lines ${citation.start_line}-${citation.end_line})\n\n[Full source file text verified in repository index]`;
  }
}

function inspectChunk(chunk) {
  const badge = document.getElementById("inspector-badge");
  const content = document.getElementById("inspector-content");
  if (!badge || !content) return;

  badge.textContent = `${chunk.path} : L${chunk.start_line}-${chunk.end_line}`;
  content.textContent = chunk.text;
}

async function handleAssistantSubmit({ analysisId, mode, question, filePath, threadContainer, sendBtn, queryInput }) {
  // Push user message
  const userText = question || `Run ${mode} on ${filePath || "repository"}`;
  activeMessages.push({
    role: "user",
    text: userText,
    mode,
    file: filePath,
  });
  renderThreadMessages(threadContainer);

  sendBtn.disabled = true;
  sendBtn.textContent = "Analyzing...";

  try {
    const resp = await api.postAssistantQuery(analysisId, {
      mode,
      question: question || "",
      file_path: filePath || null,
    });

    const data = resp.data || {};
    activeMessages.push({
      role: "assistant",
      text: data.answer || "No response received.",
      citations: data.citations || [],
      chunks: data.chunks || [],
      warnings: data.warnings || [],
      flagged: data.flagged || false,
      note: data.note || null,
      mode: data.mode || mode,
    });

    queryInput.value = "";
  } catch (err) {
    showToast(err.message || "Assistant query failed", "error");
    activeMessages.push({
      role: "assistant",
      text: `Error: ${err.message}`,
      mode,
    });
  } finally {
    sendBtn.disabled = false;
    sendBtn.textContent = "Send Query";
    renderThreadMessages(threadContainer);
  }
}
